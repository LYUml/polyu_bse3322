"""Three-zone reduced transport on measured centreplane thermal and optical proxies."""
import csv
import struct

import numpy as np

from minimum_risk import HERE, LIMIT, design, load_complete, save
from thermal import record
from run import H

LENGTH = np.array([2.8, 1., 2.8])
INC = np.array([[-1.,0.],[1.,-1.],[0.,1.]])
T = np.arange(121.)


def field(case, index, quantity, unit):
    path = case['directory'] / (case['name'] + f'_1_{index}.sf')
    with path.open('rb') as f:
        labels = [record(f).decode().strip() for _ in range(3)]
        bounds = struct.unpack('<6i',record(f))
        if (labels[0],labels[2]) != (quantity,unit) or bounds[:5]!=(0,132,9,9,0) or bounds[5] not in (19,38):
            raise ValueError(path)
        t,frames=[],[]
        while f.peek(1):
            t.append(struct.unpack('<f',record(f))[0])
            frames.append(np.frombuffer(record(f),dtype='<f4').reshape(-1,133))
    if len(t)!=121 or not np.allclose(t,T,atol=.03):
        raise ValueError(f'Incomplete or unsupported frames: {path}')
    return np.array(t),np.array(frames,dtype=float)


def observed(case):
    time,u=field(case,2,'U-VELOCITY','m/s')
    depth=.24+.08*case['design'][4]
    dz=H/(u.shape[1]-1)
    # Shared signed flux in +x, integrated only through the gap below each curtain.
    gap=np.clip(H-depth-np.arange(u.shape[1]-1)*dz,0,dz)
    states,fluxes=[],[]
    for idx,label,unit,ambient in [(1,'TEMPERATURE','C',27.5),(5,'SOOT EXTINCTION COEFFICIENT','1/m',0)]:
        stamp,f=field(case,idx,label,unit)
        np.testing.assert_allclose(stamp,time,atol=.001,rtol=0)
        f-=ambient
        centres=(f[:,1:,1:]+f[:,:-1,1:]+f[:,1:,:-1]+f[:,:-1,:-1])/4
        states.append(np.column_stack([centres[:,:,a:b].mean(axis=(1,2)) for a,b in [(0,56),(56,76),(76,132)]]))
        faces=(u*f)[:,:,[56,76]]
        fluxes.append(((faces[:,1:]+faces[:,:-1])*gap[None,:,None]/2).sum(axis=1)/H)
    return time,np.array(states),np.array(fluxes)


def nnls2(a,b):
    # Two-coefficient nonnegative least squares including both active-set edges.
    fit=np.linalg.lstsq(a,b,rcond=None)[0]
    options=[np.zeros(2)]
    if np.all(fit>=0):
        options.append(fit)
    for k in range(2):
        unit=np.zeros(2)
        unit[k]=max(0,a[:,k]@b/max(1e-16,a[:,k]@a[:,k]))
        options.append(unit)
    return min(options,key=lambda v:np.linalg.norm(a@v-b))


def calibrate(t,states,fluxes,transport):
    parameters=[]
    for state,flux in zip(states,fluxes):
        faces=np.zeros((2,2))
        if transport:
            for i in range(2):
                faces[i]=nnls2(np.column_stack((state[:,i],-state[:,i+1])),flux[:,i])
        # Five-second integral form, using the observed shared flux for calibration.
        dt=np.diff(t)
        mid=(state[1:]+state[:-1])/2
        exchange=((flux[1:]+flux[:-1])/2)@INC.T if transport else np.zeros_like(mid)
        duration=dt.reshape(-1,5).sum(axis=1)
        change=np.diff(state[::5],axis=0)*LENGTH-(dt[:,None]*exchange).reshape(-1,5,3).sum(axis=1)
        integral=(mid*dt[:,None]).reshape(-1,5,3).sum(axis=1)
        local=[nnls2(np.column_stack((duration,-integral[:,j])),change[:,j]) for j in range(3)]
        parameters.append(np.vstack([faces,local]))
    return np.array(parameters)


def rollout(params):
    traces=[]
    for p in params:
        # L_j dc_j/dt = source_j - loss_j*c_j + incoming - outgoing.
        F=np.zeros((2,3))
        for i in range(2):
            F[i,i:i+2]=p[i]*[1,-1]
        np.testing.assert_allclose((INC@F).sum(axis=0),0,atol=1e-10)
        A=(INC@F-np.diag(p[2:,1]))/LENGTH[:,None]
        step=np.linalg.inv(np.eye(3)-A)
        c=np.zeros((121,3))
        for i in range(120):
            c[i+1]=step@(c[i]+p[2:,0]/LENGTH)
        traces.append(c)
    return np.array(traces)


def signals(trace):
    return np.r_[trace.mean(axis=1).ravel(),trace.max(axis=1).ravel()]


def decode(coords, query, target):
    def kernel(x):
        return np.exp(-.5*((x[:,None]-coords[None,:])**2).sum(axis=2))
    w=np.linalg.solve(kernel(coords)+.25*np.eye(len(coords)),target-target.mean(axis=0))
    return target.mean(axis=0)+(kernel(query[None,:])@w)[0]


def main():
    with (HERE/'minimum_risk_holdouts.csv').open() as f:
        reference=list(csv.DictReader(f))
    cases=load_complete()
    cohort=[cases[r['case']] for r in reference]
    observations=[observed(c) for c in cohort]
    designs=np.array([c['design'] for c in cohort])
    targets=np.array([c['y'].min(axis=0) for c in cohort])
    rows=[]
    for transport in (False,True):
        params=np.array([calibrate(*v,transport) for v in observations])
        # Train the height decoder on proxy trajectories generated by the same
        # model class. Only training designs' fitted parameters enter each fold.
        summaries=np.array([signals(rollout(p)) for p in params])
        for i,c in enumerate(cohort):
            mask=np.any(designs[:,:-1]!=designs[i,:-1],axis=1)
            distance=((designs[mask]-designs[i])**2).sum(axis=1)
            weights=np.exp(-.5*(distance-distance.min()))
            pred=rollout(np.average(params[mask],axis=0,weights=weights))
            mu=summaries[mask].mean(axis=0)
            scale=np.maximum(summaries[mask].std(axis=0),1e-8)*np.sqrt(len(mu))
            coords=np.column_stack((designs[mask],(summaries[mask]-mu)/scale))
            h=decode(coords,np.r_[designs[i],(signals(pred)-mu)/scale],targets[mask])
            errors=np.mean(abs(pred-observations[i][1]),axis=(1,2))
            rows.append(dict(case=c['name'],exchange=int(transport),actual_min_m=targets[i].min(),
                             predicted_min_m=np.clip(h,0,H).min(),temperature_mae_K=errors[0],
                             extinction_mae_per_m=errors[1],previous_hybrid_m=reference[i]['hybrid_m']))
    save(HERE/'three_zone_scores.csv',rows)
    for label,rs,key in [('no flux',rows[:len(cohort)],'predicted_min_m'),
                         ('shared flux',rows[len(cohort):],'predicted_min_m'),
                         ('previous',rows[:len(cohort)],'previous_hybrid_m')]:
        a,p=np.array([[r['actual_min_m'],float(r[key])] for r in rs]).T
        print(label,'mae cm',100*np.mean(abs(p-a)),'false pass',sum((a<LIMIT)&(p>=LIMIT)),
              'false fail',sum((a>=LIMIT)&(p<LIMIT)))
        if key=='predicted_min_m':
            print('field MAEs',*[np.mean([r[k] for r in rs]) for k in ['temperature_mae_K','extinction_mae_per_m']])


if __name__=='__main__':
    main()
